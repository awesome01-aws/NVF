  await save(loss, await loss.locator('button[type="submit"]').innerText());
  assert.equal((await data()).rabbits.find(r => r.id === 'review-rabbit-loss').status, 'deceased');
  await farm('eaten'); await page.locator('#toggle_eaten_form').click();
  const meal = page.locator('#form_section_fowls_eaten');
  await meal.locator('select').selectOption('rabbit:review-rabbit-meal');
  await meal.locator('input[type="number"]').first().fill('1'); await checkPhone('rabbit-household-use');
  await save(meal, await meal.locator('button[type="submit"]').innerText());
  assert.equal((await data()).rabbits.find(r => r.id === 'review-rabbit-meal').status, 'eaten');
  await meal.locator('select').selectOption(flock.id); await meal.locator('input[type="number"]').first().fill('1');
  await save(meal, await meal.locator('button[type="submit"]').innerText());
  assert.equal((await data()).flocks.find(f => f.id === flock.id).quantity, 7);
  await farm('flocks');
  console.log('Deaths and household use verified.');
  const housing = page.getByRole('region', { name: 'Rabbit and quail cages' });
  await housing.getByLabel('Housing action').selectOption('assign');
  await housing.getByLabel('Rabbit or litter', { exact: true }).selectOption('rabbit:review-rabbit-doe');
  await housing.getByLabel('Move to', { exact: true }).selectOption('review-r2');
  await checkPhone('rabbit-housing'); await save(housing, 'Save move');
  assert.equal((await data()).rabbits.find(r => r.id === 'review-rabbit-doe').hutchId, 'review-r2');
  await housing.getByLabel('Animal type', { exact: true }).selectOption('Quail');
  await housing.getByLabel('Housing action').selectOption('create');
  await housing.getByLabel('Block or location').fill('Quail house');
  await housing.getByLabel('Cage or hutch name', { exact: true }).fill('Q2');
  await checkPhone('quail-housing-add'); await save(housing, 'Save housing');
  const q2 = (await data()).cages.find(c => c.cageName === 'Q2');
  await housing.getByLabel('Housing action').selectOption('assign');
  await housing.getByLabel('Quail flock', { exact: true }).selectOption(flock.id);
  await housing.getByLabel('Move to', { exact: true }).selectOption(q2.id);
  await save(housing, 'Save move');
  assert.equal((await data()).cage_allocations.find(c => c.flockName === 'Family quail').quantity, 7);
  await farm('rabbits');
  console.log('Housing assignments verified.');
  await page.getByLabel('Rabbit task').selectOption('rabbit_add');
  await page.getByLabel('Rabbit name', { exact: true }).fill('New doe');
  await page.getByLabel('Sex', { exact: true }).selectOption('female');
  await page.getByLabel('Birth date (if known)').fill(day(-190));
  await checkPhone('rabbit-age-form');
  await page.getByLabel('Rabbit task').selectOption('rabbit_breeding'); await checkPhone('rabbit-breeding-form');
  await page.getByLabel('Rabbit task').selectOption('rabbit_litter'); await checkPhone('rabbit-litter-form');
  await farm('quail'); await page.getByLabel('Quail task').selectOption('quail_eaten'); await checkPhone('quail-household-form');
  const childContext = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  const childPage = await childContext.newPage(); await openFarm(childPage);
  await childPage.getByRole('button', { name: 'Farm', exact: true }).filter({ visible: true }).click();
  await childPage.getByLabel('Farm section', { exact: true }).selectOption('flocks');
  await childPage.getByRole('region', { name: 'Rabbit and quail cages' }).getByText('Family quail · 7 quail', { exact: true }).waitFor();
  await farm('sales');
  if (!await sale.isVisible()) await page.locator('#toggle_sales_form').click();
  await sale.locator('select').first().selectOption('Quail'); await sale.locator('select').nth(1).selectOption(flock.id);
  await sale.locator('input[type="number"]').nth(0).fill('1'); await sale.locator('input[type="number"]').nth(1).fill('1000'); await sale.locator('input[type="text"]').first().fill('Offline buyer');
  await dadContext.setOffline(true); await sale.locator('button[type="submit"]').click();
  await page.getByRole('status').filter({ hasText: 'Saved on this phone' }).waitFor();
  assert.equal((await data()).flocks.find(f => f.id === flock.id).quantity, 7, 'Offline stock has not reached the server');
  await dadContext.setOffline(false);
  await page.reload(); await page.getByRole('heading', { name: /Hello/ }).waitFor();
  for (let i = 0; i < 60 && (await data()).flocks.find(f => f.id === flock.id).quantity !== 6; i++) await page.waitForTimeout(250);
  assert.equal((await data()).flocks.find(f => f.id === flock.id).quantity, 6);
