  assert.equal((await data()).flocks.find(f => f.id === flock.id).quantity, 6, 'Replay cannot deduct stock twice');
  await farm('sales');
  const rabbitSaleRow = page.locator('#section_sales tbody tr').filter({ has: page.getByText('Rabbit', { exact: true }) });
  await rabbitSaleRow.getByTitle('Reverse sale and restore stock', { exact: true }).click();
  const reversal = page.waitForResponse(r => r.url().endsWith('/api/farm/actions') && r.request().method() === 'POST');
  await page.getByRole('button', { name: /reverse record/i }).click();
  assert.equal((await reversal).status(), 200);
  assert.equal((await data()).rabbits.find(r => r.id === 'review-rabbit-sale').status, 'active');
  console.log('Shared-table reversal verified.');
  await page.getByRole('button', { name: 'Home', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: /Correct cage count/ }).click();
